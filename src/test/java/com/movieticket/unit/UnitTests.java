/** Plain unit tests: no Spring context, no database. */
class UnitTests {

    // ------------------------------------------------------------------ payment simulator
    @Test
    @DisplayName("Simulator: each test card produces its documented outcome")
    void simulatorOutcomes() {
        SimulatedPaymentGateway gw = new SimulatedPaymentGateway(TestProps.with(1.0, 0, true));
        BigDecimal amount = new BigDecimal("150.00");

        assertThat(gw.charge(1L, amount, PaymentMethod.TEST_SUCCESS).outcome()).isEqualTo(Outcome.SUCCESS);
        assertThat(gw.charge(1L, amount, PaymentMethod.TEST_CAPTURE_THEN_FAIL).outcome()).isEqualTo(Outcome.SUCCESS);
        assertThat(gw.charge(1L, amount, PaymentMethod.TEST_DECLINED).outcome()).isEqualTo(Outcome.DECLINED);
        assertThat(gw.charge(1L, amount, PaymentMethod.TEST_TIMEOUT).outcome()).isEqualTo(Outcome.TIMEOUT);
        GatewayResult ok = gw.charge(1L, amount, PaymentMethod.TEST_SUCCESS);
        assertThat(ok.reference()).startsWith("SIM-"); // clearly marked as simulated
        assertThat(gw.refund(ok.reference(), amount).isSuccess()).isTrue();
    }

    @Test
    @DisplayName("Simulator: TEST_RANDOM honours the configured success rate at the extremes")
    void simulatorRandom() {
        SimulatedPaymentGateway alwaysOk = new SimulatedPaymentGateway(TestProps.with(1.0, 0, true));
        SimulatedPaymentGateway neverOk = new SimulatedPaymentGateway(TestProps.with(0.0, 0, true));
        for (int i = 0; i < 50; i++) {
            assertThat(alwaysOk.charge(1L, BigDecimal.TEN, PaymentMethod.TEST_RANDOM).isSuccess()).isTrue();
            assertThat(neverOk.charge(1L, BigDecimal.TEN, PaymentMethod.TEST_RANDOM).isSuccess()).isFalse();
        }
    }

    // ------------------------------------------------------------------ hashing, validation, JWT
    @Test
    @DisplayName("RequestHasher is deterministic and sensitive to every input")
    void hasher() {
        assertThat(RequestHasher.sha256Hex("1|2|3")).isEqualTo(RequestHasher.sha256Hex("1|2|3")).hasSize(64);
        assertThat(RequestHasher.sha256Hex("1|2|3")).isNotEqualTo(RequestHasher.sha256Hex("1|2|4"));
    }

    @Test
    @DisplayName("Password rule: 8+ chars with a letter and a digit")
    void passwordRule() {
        StrongPasswordValidator v = new StrongPasswordValidator();
        assertThat(v.isValid("Secret123", null)).isTrue();
        assertThat(v.isValid("short1", null)).isFalse();
        assertThat(v.isValid("onlyletters", null)).isFalse();
        assertThat(v.isValid("12345678", null)).isFalse();
        assertThat(v.isValid("x".repeat(80) + "1", null)).isFalse(); // beyond BCrypt's 72-byte limit
    }

    @Test
    @DisplayName("JWT: round trip works, tampered or foreign-signed tokens are rejected, short secret refuses to start")
    void jwt() {
        JwtService service = new JwtService(TestProps.with(1, 0, true));
        User user = new User("N", "n@test.local", "hash", Role.ADMIN, LocalDateTime.now());
        ReflectionTestUtils.setField(user, "id", 7L); // normally generated by MySQL on insert
        String token = service.generateToken(user);
        assertThat(service.parse(token)).isPresent();
        assertThat(service.parse(token).get().role()).isEqualTo(Role.ADMIN);
        assertThat(service.parse(token).get().id()).isEqualTo(7L);
        assertThat(service.parse(token + "x")).isEmpty();
        assertThat(service.parse("garbage")).isEmpty();

        var other = new com.movieticket.config.AppProperties(
                new com.movieticket.config.AppProperties.Jwt("a-completely-different-secret-value-0123456789", 60),
                null, null, null, null, null, null, null, null);
        assertThat(new JwtService(other).parse(token)).isEmpty();

        var weak = new com.movieticket.config.AppProperties(new com.movieticket.config.AppProperties.Jwt("tiny", 60),
                null, null, null, null, null, null, null, null);
        assertThatThrownBy(() -> new JwtService(weak)).isInstanceOf(IllegalStateException.class).hasMessageContaining("JWT_SECRET");
    }

    @Test
    void authenticatedUserRole() {
        assertThat(new AuthenticatedUser(1L, "a", Role.ADMIN).isAdmin()).isTrue();
        assertThat(new AuthenticatedUser(1L, "a", Role.USER).isAdmin()).isFalse();
    }

    // ------------------------------------------------------------------ outbox relay (RabbitMQ mocked)
    private static TransactionTemplate fakeTx() {
        PlatformTransactionManager manager = mock(PlatformTransactionManager.class);
        when(manager.getTransaction(any())).thenReturn(new SimpleTransactionStatus());
        return new TransactionTemplate(manager);
    }

    private static OutboxEvent event(String payload) {
        return new OutboxEvent(EventType.SEAT_LOCKED, 1L, payload, LocalDateTime.now());
    }

    @Test
    @DisplayName("Outbox relay: delivered events are marked PUBLISHED")
    void relayMarksPublished() throws Exception {
        OutboxEventRepository repo = mock(OutboxEventRepository.class);
        EventMessagePublisher publisher = mock(EventMessagePublisher.class);
        OutboxEvent a = event("{}");
        OutboxEvent b = event("{}");
        when(repo.lockPending(10)).thenReturn(List.of(a, b));

        int delivered = new OutboxRelay(repo, publisher, fakeTx(), TestProps.with(1, 0, true), Clock.systemDefaultZone()).relayPending();

        assertThat(delivered).isEqualTo(2);
        assertThat(a.getStatus()).isEqualTo(OutboxStatus.PUBLISHED);
        assertThat(b.getStatus()).isEqualTo(OutboxStatus.PUBLISHED);
        assertThat(a.getPublishedAt()).isNotNull();
    }

    @Test
    @DisplayName("Outbox relay: when the broker is down the event stays PENDING, the failure is recorded and later events are not skipped ahead")
    void relayKeepsPendingOnFailure() throws Exception {
        OutboxEventRepository repo = mock(OutboxEventRepository.class);
        EventMessagePublisher publisher = mock(EventMessagePublisher.class);
        OutboxEvent a = event("{}");
        OutboxEvent b = event("{}");
        when(repo.lockPending(10)).thenReturn(List.of(a, b));
        doThrow(new IllegalStateException("broker down")).when(publisher).publish(a);

        int delivered = new OutboxRelay(repo, publisher, fakeTx(), TestProps.with(1, 0, true), Clock.systemDefaultZone()).relayPending();

        assertThat(delivered).isZero();
        assertThat(a.getStatus()).isEqualTo(OutboxStatus.PENDING);
        assertThat(a.getAttempts()).isEqualTo(1);
        assertThat(a.getLastError()).contains("broker down");
        assertThat(b.getStatus()).isEqualTo(OutboxStatus.PENDING);
        verify(publisher, never()).publish(b); // ordering preserved
    }

    @Test
    void eventTypesHaveRoutingKeys() {
        for (EventType t : EventType.values()) {
            assertThat(t.routingKey()).contains(".");
            assertThat(t.displayName()).isNotBlank();
        }
        assertThat(EventType.values()).extracting(EventType::displayName).contains("SeatLocked", "BookingCreated",
                "PaymentCompleted", "PaymentFailed", "SeatReleased", "BookingConfirmed", "BookingCancelled");
    }
}
